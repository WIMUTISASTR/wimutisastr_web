-- ── 4. Verify ─────────────────────────────────────────────────
SELECT
  vc.name                                      AS course,
  COUNT(v.id)                                  AS total_videos,
  COUNT(v.id) FILTER (WHERE v.access_level = 'free')    AS free_videos,
  COUNT(v.id) FILTER (WHERE v.access_level = 'members') AS member_videos
FROM video_categories vc
LEFT JOIN videos v ON v.category_id = vc.id
GROUP BY vc.id, vc.name
ORDER BY vc.name;
